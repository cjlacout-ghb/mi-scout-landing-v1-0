function detectarIdioma() {
  const guardado = localStorage.getItem('miscout_lang');
  if (guardado === 'es' || guardado === 'en') return guardado;
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('en') ? 'en' : 'es';
}

function aplicarIdioma(lang) {
  const dict = MISCOUT_I18N[lang];
  if (!dict) {
    console.warn('[MiScoutI18n] Idioma desconocido:', lang);
    return;
  }

  // data-i18n → textContent
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const clave = el.getAttribute('data-i18n');
    if (clave in dict) {
      el.textContent = dict[clave];
    } else {
      console.warn('[MiScoutI18n] Clave no encontrada en "' + lang + '":', clave);
    }
  });

  // data-i18n-placeholder → placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    const clave = el.getAttribute('data-i18n-placeholder');
    if (clave in dict) {
      el.setAttribute('placeholder', dict[clave]);
    } else {
      console.warn('[MiScoutI18n] Clave no encontrada en "' + lang + '":', clave);
    }
  });

  // data-i18n-attr-content → content
  document.querySelectorAll('[data-i18n-attr-content]').forEach(function (el) {
    const clave = el.getAttribute('data-i18n-attr-content');
    if (clave in dict) {
      el.setAttribute('content', dict[clave]);
    } else {
      console.warn('[MiScoutI18n] Clave no encontrada en "' + lang + '":', clave);
    }
  });

  // data-i18n-attr-alt → alt
  document.querySelectorAll('[data-i18n-attr-alt]').forEach(function (el) {
    const clave = el.getAttribute('data-i18n-attr-alt');
    if (clave in dict) {
      el.setAttribute('alt', dict[clave]);
    } else {
      console.warn('[MiScoutI18n] Clave no encontrada en "' + lang + '":', clave);
    }
  });

  // Footer dinámico Idioma
  const footerLangLabel = document.getElementById('footer-lang-label');
  const footerLangValue = document.getElementById('footer-lang-value');
  if (footerLangLabel && footerLangValue) {
    footerLangLabel.textContent = dict['footer_meta_lang_label'] || footerLangLabel.textContent;
    footerLangValue.textContent = dict['footer_meta_lang_value'] || footerLangValue.textContent;
  }

  // Link a la Guía de Usuario
  const guideBtn = document.getElementById('guide-btn-link');
  if (guideBtn) {
    guideBtn.setAttribute('href', lang === 'en' ? 'Guia_de_Usuario_EN.html' : 'Guia_de_Usuario.html');
  }

  // Swap de imágenes (data-src-en, data-href-en, data-images-en)
  document.querySelectorAll('[data-src-en]').forEach(el => {
    if (!el.hasAttribute('data-src-es')) {
      el.setAttribute('data-src-es', el.getAttribute('src'));
    }
    el.setAttribute('src', lang === 'en' ? el.getAttribute('data-src-en') : el.getAttribute('data-src-es'));
  });

  document.querySelectorAll('[data-href-en]').forEach(el => {
    if (!el.hasAttribute('data-href-es')) {
      el.setAttribute('data-href-es', el.getAttribute('href'));
    }
    el.setAttribute('href', lang === 'en' ? el.getAttribute('data-href-en') : el.getAttribute('data-href-es'));
  });

  document.querySelectorAll('[data-images-en]').forEach(el => {
    if (!el.hasAttribute('data-images-es')) {
      el.setAttribute('data-images-es', el.getAttribute('data-images'));
    }
    el.setAttribute('data-images', lang === 'en' ? el.getAttribute('data-images-en') : el.getAttribute('data-images-es'));
  });

  // Actualizar lang en <html>
  document.documentElement.setAttribute('lang', lang);

  // Persistir
  localStorage.setItem('miscout_lang', lang);

  // Actualizar UI de botones (si ya están en el DOM)
  if (typeof actualizarBotonesIdioma === 'function') {
    actualizarBotonesIdioma(lang);
  }
}

function actualizarBotonesIdioma(lang) {
  const btnEsDesk = document.getElementById('lang-toggle-es');
  const btnEnDesk = document.getElementById('lang-toggle-en');
  const btnEsMob = document.getElementById('lang-toggle-es-mobile');
  const btnEnMob = document.getElementById('lang-toggle-en-mobile');

  // Quitar active de todos
  [btnEsDesk, btnEnDesk, btnEsMob, btnEnMob].forEach(btn => {
    if (btn) btn.classList.remove('active');
  });

  // Agregar active al seleccionado
  if (lang === 'es') {
    if (btnEsDesk) btnEsDesk.classList.add('active');
    if (btnEsMob) btnEsMob.classList.add('active');
  } else if (lang === 'en') {
    if (btnEnDesk) btnEnDesk.classList.add('active');
    if (btnEnMob) btnEnMob.classList.add('active');
  }
}

function inicializarIdioma() {
  const lang = detectarIdioma();
  aplicarIdioma(lang);
  // Revelar el body una vez aplicado el idioma (anti-FOUC)
  document.body.style.visibility = 'visible';

  // Configurar listeners de UI
  const btnEsDesk = document.getElementById('lang-toggle-es');
  const btnEnDesk = document.getElementById('lang-toggle-en');
  const btnEsMob = document.getElementById('lang-toggle-es-mobile');
  const btnEnMob = document.getElementById('lang-toggle-en-mobile');

  if (btnEsDesk) btnEsDesk.addEventListener('click', () => aplicarIdioma('es'));
  if (btnEnDesk) btnEnDesk.addEventListener('click', () => aplicarIdioma('en'));
  if (btnEsMob) btnEsMob.addEventListener('click', () => aplicarIdioma('es'));
  if (btnEnMob) btnEnMob.addEventListener('click', () => aplicarIdioma('en'));
}

// Sobrescribir aplicarIdioma original para agregar la llamada a UI
const originalAplicarIdioma = window.MiScoutI18n ? window.MiScoutI18n.aplicarIdioma : null;

// Re-exportar API pública si se desea
window.MiScoutI18n = {
  aplicarIdioma: aplicarIdioma,
  detectarIdioma: detectarIdioma,
  inicializarIdioma: inicializarIdioma
};

// Auto-init en cuanto el DOM esté listo
document.addEventListener('DOMContentLoaded', inicializarIdioma);
